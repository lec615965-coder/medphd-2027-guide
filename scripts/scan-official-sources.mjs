import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const dataDirectory = new URL("data/", root);
const snapshotsPath = new URL("source-snapshots.json", dataDirectory);
const monitorPath = new URL("monitor.json", dataDirectory);
const noticesPath = new URL("notices.json", dataDirectory);
const sourcesPath = new URL("sources.json", dataDirectory);
const requestTimeoutMs = 15_000;

const readJson = async (url, fallback) => {
  try {
    return JSON.parse(await readFile(url, "utf8"));
  } catch (error) {
    if (error?.code === "ENOENT") return fallback;
    throw error;
  }
};

const writeJson = (url, value) => writeFile(url, JSON.stringify(value, null, 2) + "\n", "utf8");

const chinaDate = (date) => {
  const fields = new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Shanghai", year: "numeric", month: "2-digit", day: "2-digit"
  }).formatToParts(date).reduce((result, part) => ({ ...result, [part.type]: part.value }), {});
  return `${fields.year}-${fields.month}-${fields.day}`;
};

const normalizePage = (html) => html
  .replace(/<!--[\s\S]*?-->/g, " ")
  .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, " ")
  .replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, " ")
  .replace(/\s+/g, " ")
  .trim()
  .slice(0, 1_500_000);

const pageTitle = (html) => {
  const match = html.match(/<title\b[^>]*>([\s\S]*?)<\/title>/i);
  return (match?.[1] || "官方来源页面")
    .replace(/<[^>]+>/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 120);
};

const isPermittedUrl = (value) => {
  const url = new URL(value);
  if (!['http:', 'https:'].includes(url.protocol)) throw new Error("Only HTTP(S) source URLs are permitted");
  return url;
};

const equivalentHost = (requested, resolved) =>
  requested === resolved || requested.endsWith(`.${resolved}`) || resolved.endsWith(`.${requested}`);

const scanSource = async (source) => {
  const sourceUrl = isPermittedUrl(source.url);
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), requestTimeoutMs);
  try {
    const response = await fetch(sourceUrl, {
      signal: controller.signal,
      headers: { "User-Agent": "medphd-2027-guide-monitor/1.0 (+https://lec615965-coder.github.io/medphd-2027-guide/)" }
    });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const resolved = new URL(response.url);
    if (!equivalentHost(sourceUrl.hostname, resolved.hostname)) {
      throw new Error(`Redirected to an unregistered host: ${resolved.hostname}`);
    }
    const html = await response.text();
    const normalized = normalizePage(html);
    if (!normalized) throw new Error("Empty source response");
    return {
      hash: createHash("sha256").update(normalized).digest("hex"),
      title: pageTitle(html),
      resolvedUrl: resolved.toString()
    };
  } finally {
    clearTimeout(timer);
  }
};

const sourceUpdateNotice = (source, page, date) => ({
  id: `auto-source-update-${source.id}`,
  sourceId: source.id,
  title: `${source.name}官方招生来源检测到页面变化`,
  summary: `自动监测于 ${date} 发现已登记官方来源页面内容变化（页面标题：${page.title || "官方来源页面"}）。本站已直接公开原文入口，请以院校官方通知为准。`,
  publishedAt: date,
  degreeType: source.degreeTypes.join(" · "),
  degreeTypes: source.degreeTypes,
  field: "官方来源自动更新",
  url: source.url,
  autoGenerated: true
});

await mkdir(dataDirectory, { recursive: true });
const now = new Date();
const checkedAt = now.toISOString();
const publishedAt = chinaDate(now);
const [sources, notices, monitor, savedSnapshots] = await Promise.all([
  readJson(sourcesPath, []),
  readJson(noticesPath, []),
  readJson(monitorPath, {}),
  readJson(snapshotsPath, { version: 1, sources: {} })
]);
const snapshots = savedSnapshots?.sources || {};
let baselineCount = 0;
let changedCount = 0;
let unchangedCount = 0;
let failedCount = 0;

for (const source of sources) {
  const previous = snapshots[source.id];
  try {
    const page = await scanSource(source);
    snapshots[source.id] = {
      hash: page.hash,
      title: page.title,
      sourceUrl: source.url,
      resolvedUrl: page.resolvedUrl,
      lastCheckedAt: checkedAt,
      lastSuccessAt: checkedAt,
      status: previous?.hash === page.hash ? "unchanged" : previous?.hash ? "changed" : "baseline"
    };
    if (!previous?.hash) {
      baselineCount += 1;
      continue;
    }
    if (previous.hash === page.hash) {
      unchangedCount += 1;
      continue;
    }
    changedCount += 1;
    const nextNotice = sourceUpdateNotice(source, page, publishedAt);
    const existingIndex = notices.findIndex((notice) => notice.id === nextNotice.id);
    if (existingIndex === -1) notices.unshift(nextNotice);
    else notices[existingIndex] = nextNotice;
  } catch (error) {
    failedCount += 1;
    snapshots[source.id] = {
      ...previous,
      sourceUrl: source.url,
      lastCheckedAt: checkedAt,
      status: "failed",
      lastError: String(error?.message || error).slice(0, 240)
    };
  }
}

monitor.siteStatus = failedCount ? "automated-publication-with-alerts" : "automated-publication";
monitor.lastCheckedAt = checkedAt;
monitor.message = `自动扫描 ${sources.length} 个已登记官方来源：首次建立基线 ${baselineCount} 个，检测到并已自动公开 ${changedCount} 个来源变化，未变化 ${unchangedCount} 个，抓取失败或访问受限 ${failedCount} 个。失败来源保留既有公开信息。`;
monitor.policy = "自动公开已登记官方来源的可追溯页面变化提示；抓取失败不删除既有信息。招生政策与时间节点以院校官方最终通知为准。";

await Promise.all([
  writeJson(snapshotsPath, { version: 1, updatedAt: checkedAt, sources: snapshots }),
  writeJson(noticesPath, notices),
  writeJson(monitorPath, monitor)
]);

console.log(JSON.stringify({ checkedAt, baselineCount, changedCount, unchangedCount, failedCount }));

